export type OgCard = {
  /** Eight words or fewer; `*words*` in the brand colour. */
  readonly title: string;
  /** One sentence under the headline, on cards with room for it. */
  readonly deck?: string;
  /** Overrides the kind label in the eyebrow, e.g. "Engineering". */
  readonly eyebrow?: string;
  readonly figure: Figure;
};

const eyebrowLabels: Record<CanonicalRoute["kind"], string> = {
  home: "AI employee",
  page: "Company",
  pricing: "Pricing",
  "use-case": "Use case",
  tool: "Free tool",
  "tool-index": "Free tools",
  "blog-index": "Blog",
  "blog-post": "Article",
  guide: "Guide",
  comparison: "Comparison",
  "author-index": "Authors",
  author: "Author",
  tag: "Topic",
};

const postKinds = new Set(["blog-post", "guide", "comparison"]);
const count = (route: CanonicalRoute, routes: readonly CanonicalRoute[]) =>
  members(route, routes)?.length ?? 0;

/**
 * Topics with two or more posts, drafts included, get a mosaic of their
 * posts' cards, so a new topic has its card the moment its hub exists.
 */
function topicCards(): Record<string, OgCard> {
  const tags = blogMetadata.flatMap((post) => post.tags);
  return Object.fromEntries(
    [...new Set(tags)]
      .filter((tag) => tags.filter((entry) => entry === tag).length >= 2)
      .map((tag) => [
        `blog-tag-${tag}`,
        { title: tagLabel(tag), figure: { kind: "mosaic" } },
      ]),
  );
}

/** An author's three most used tags, most used first. */
function topicsOf(id: string): string[] {
  const counts = new Map<string, number>();
  for (const post of blogMetadata) {
    if (post.author !== id) continue;
    for (const tag of post.tags) counts.set(tag, (counts.get(tag) ?? 0) + 1);
  }
  return [...counts]
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .slice(0, 3)
    .map(([tag]) => tagLabel(tag));
}

function authorCards(): Record<string, OgCard> {
  return Object.fromEntries(
    authorIds.map((id) => {
      const author = authors[id];
      return [
        `authors-${id}`,
        {
          title: author.name,
          deck: author.bio,
          figure: {
            kind: "profile",
            name: author.name,
            role: author.role,
            handle: author.twitterHandle,
            topics: topicsOf(id),
            ...(author.schemaType === "Person" ? { photo: author.image } : {}),
          },
        },
      ];
    }),
  );
}

