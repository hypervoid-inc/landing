export function figureKind(name: string): FigureKind | undefined {
  return ogCards[name]?.figure.kind;
}

/** What a card is rendered with besides its own content. */
export type CardContext = {
  readonly eyebrow: readonly string[];
  /** A mosaic's pages, newest first, by their published card's stem. */
  readonly members?: readonly { readonly stem: string }[];
  readonly count?: number;
};

const SHOWN = 4;

function formatDate(date: string): string {
  return new Date(`${date}T00:00:00Z`).toLocaleDateString("en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
    timeZone: "UTC",
  });
}

/**
 * `routes` is every route that exists or is scheduled to, the same list the
 * publisher and the OG tests use, so a topic card does not go stale on the
 * morning one of its posts goes live. Only a post's card prints a date.
 */
export function cardContext(
  route: CanonicalRoute,
  routes: readonly CanonicalRoute[],
  card: OgCard,
): CardContext {
  const label = card.eyebrow ?? eyebrowLabels[route.kind];
  const eyebrow =
    postKinds.has(route.kind) && route.published
      ? [label, formatDate(route.published)]
      : [label];
  if (card.figure.kind !== "mosaic") return { eyebrow };
  const listed = members(route, routes) ?? [];
  return {
    eyebrow,
    count: count(route, routes),
    members: listed.slice(0, SHOWN).map((page) => ({
      stem: new URL(page.image).pathname
        .split("/")
        .pop()!
        .replace(/\.jpg$/, ""),
    })),
  };
}

const newestFirst = (left: CanonicalRoute, right: CanonicalRoute) =>
  (right.published ?? "").localeCompare(left.published ?? "") ||
  left.path.localeCompare(right.path);

/** The pages a topic or an index lists, in the order it lists them. */
function members(
  route: CanonicalRoute,
  routes: readonly CanonicalRoute[],
): readonly CanonicalRoute[] | undefined {
  switch (route.kind) {
    case "tag": {
      const tag = route.tags?.[0];
      return routes
        .filter(
          (post) => postKinds.has(post.kind) && tag && post.tags?.includes(tag),
        )
        .sort(newestFirst);
    }
    case "blog-index":
      return routes
        .filter((post) => postKinds.has(post.kind))
        .sort(newestFirst);
    case "tool-index":
      return routes.filter((page) => page.kind === "tool");
    case "author-index":
      return routes.filter((page) => page.kind === "author");
    case "use-case":
      return route.path === "/use-cases"
        ? routes.filter(
            (page) => page.kind === "use-case" && page.path !== route.path,
          )
        : undefined;
    default:
      return undefined;
  }
}
